import { randomBytes } from 'node:crypto';

/**
 * Ключ AES для чек-ин кодов: в проде — env CHECKIN_ENC_KEY. Локально без
 * ключа — случайный на время жизни процесса: окна живут 3 минуты, потеря
 * при рестарте внутри окна редка и не страшна (прод задаёт ключ явно).
 * Один на процесс: код шифрует запуск окна при смене статуса, а показывает
 * контроллер чек-ина — разные ключи сделали бы код нечитаемым.
 */
export const CHECKIN_ENC_KEY = process.env.CHECKIN_ENC_KEY || randomBytes(32).toString('hex');
